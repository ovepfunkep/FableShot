import { expect, test } from '@playwright/test';
import { openHistoryEntry, openTraining } from './journal-navigation.ts';

test('numbered kit records hits first, prevents duplicates and edits old assignments', async ({ page }) => {
  await page.goto('./');
  await page.getByTestId('home-change-conditions').click();
  await page.getByTestId('conditions-equipment').click();
  await page.getByTestId('equipment-add-choice').click();
  await page.getByTestId('equipment-name').fill('Мой комплект');
  await page.getByRole('button', { name: 'Добавить стрелы', exact: true }).click();
  await page.getByTestId('equipment-name').fill('Пронумерованные');
  await page.getByTestId('equipment-numbered-count').fill('6');
  await page.getByTestId('equipment-component-save').click();
  await page.getByTestId('equipment-save').click();
  await page.getByTestId('start-training').click();

  const miss = page.getByRole('button', { name: 'Отметить промах' });
  const picker = page.getByTestId('physical-arrow-picker');
  const number = (value: number) => page.getByTestId(`physical-arrow-quick-${value}`);
  await page.getByTestId('target').click();
  await expect(page.getByTestId('series-score')).toHaveText('10/10');
  await expect(picker).toBeVisible();
  await number(3).click();
  await miss.click();
  await expect(number(3)).toBeDisabled();
  await page.keyboard.press('Escape');
  await expect(page.getByTestId('series-score')).toHaveText('10/20');
  await expect(page.getByTestId('shot-2')).toHaveAccessibleName('Стрела 2: M');
  await page.getByTestId('next-end').click();
  await miss.click();
  await number(3).click();
  await page.getByRole('button', { name: 'Завершить тренировку' }).click();
  await page.getByTestId('training-confirm').click();
  await page.reload();
  await openHistoryEntry(page);
  await expect(page.getByTestId('numbered-arrow-analysis')).toBeVisible();
  await page.getByTestId('numbered-arrow-3').click();
  await expect(page.getByTestId('numbered-arrow-point')).toHaveCount(1);
  await page.getByTestId('numbered-arrow-details').click();
  await expect(page.getByTestId('numbered-arrow-analysis')).toContainText('Скрыть подробности');
  await page.locator('[data-testid^="report-end-"]').first().click();
  await expect(page.getByTestId('history-shot-editor')).toBeVisible();
  await expect(page.getByTestId('next-end')).toBeDisabled();
  await page.getByTestId('target').click();
  await expect(page.getByTestId('next-end')).toBeDisabled();
  await page.getByTestId('shot-1').click();
  await page.getByTestId('physical-arrow-choice').click();
  await expect(number(3)).toHaveAttribute('aria-pressed', 'true');
  await number(4).click();
  await page.getByTestId('next-end').click();
  await expect(page.getByTestId('shot-1')).toHaveAccessibleName('Стрела 1: 10, физическая стрела №4');
  await page.getByTestId('physical-arrow-choice').click();
  await number(4).click();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog', { name: 'Отменить правки?' })).toBeVisible();
  await page.getByTestId('training-confirm').click();
  await expect(page.getByTestId('shot-1')).toHaveAccessibleName('Стрела 1: 10, физическая стрела №4');
  await page.getByTestId('shot-1').click();
  await page.getByTestId('physical-arrow-choice').click();
  await number(4).click();
  await page.getByTestId('next-end').click();
  await expect(page.getByTestId('shot-1')).toHaveAccessibleName('Стрела 1: 10');

  await page.getByTestId('shot-1').click();
  await page.getByRole('button', { name: 'Закрыть редактор' }).click();
  await page.getByRole('button', { name: 'Назад', exact: true }).click();
  await page.getByTestId('nav-home').click();
  await openTraining(page);
  await page.getByRole('button', { name: 'Условия тренировки', exact: true }).click();
  await page.getByTestId('conditions-options').click();
  await page.getByTestId('conditions-advanced').click();
  const toggle = page.getByTestId('numbered-arrows-toggle');
  await expect(toggle).toHaveAttribute('aria-checked', 'true');
  await toggle.click();
  await page.getByTestId('conditions-options-done').click();
  await page.getByTestId('start-training').click();
  await page.reload();
  await openTraining(page);
  await miss.click();
  await expect(page.getByTestId('series-score')).toHaveText('0/10');
  await expect(miss).toBeEnabled();
  await expect(picker).toHaveCount(0);
});
