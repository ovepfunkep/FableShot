"""Rebuild the supported score-reference catalog from the preserved Ministry XLS.

Read-only extraction: requires xlrd (local .tools/rank-reader is supported).
No inferred thresholds or unsupported multi-distance/3D formats.
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / '.tools/rank-reader'))
import xlrd

source = ROOT / 'docs/references/evsk-archery-2026.xls'
sheet = xlrd.open_workbook(source).sheet_by_name('Нормы КЛ БЛ')
# One-based XLS rows; all selected formats use a single distance, max 10 per arrow.
formats = [
    ('recurve-18-30', 'recurve', 18, 30, 11),
    ('recurve-18-60', 'recurve', 18, 60, 12),
    ('barebow-18-30', 'barebow', 18, 30, 25),
    ('barebow-18-60', 'barebow', 18, 60, 26),
    ('compound-18-30', 'compound', 18, 30, 29),
    ('compound-18-60', 'compound', 18, 60, 30),
    ('recurve-70-72', 'recurve', 70, 72, 18),
    ('compound-50-72', 'compound', 50, 72, 31),
    ('compound-70-72', 'compound', 70, 72, 37),
]
labels = ['МСМК', 'МС', 'КМС', 'I', 'II', 'III', 'I юн.', 'II юн.', 'III юн.']
lines = []
for key, bow, distance, count, row in formats:
    for sex, offset in [('male', 0), ('female', 1)]:
        thresholds = []
        for i, label in reversed(list(enumerate(labels))):
            value = sheet.cell_value(row - 1, 4 + 2 * i + offset)
            if value != '':
                value = float(value)
                assert value.is_integer() and 0 < value <= count * 10
                thresholds.append(f'RankThreshold("{label}", {int(value)})')
        assert thresholds
        lines.append(f'        RankExercise("{key}-{sex}", "{bow}", {distance}, {count}, "{sex}", {row}, listOf(' + ', '.join(thresholds) + ')),')
code = '''package app.fableshot.android.domain

/** Generated by scripts/extract-rank-catalog.py from the preserved Ministry workbook.
 * Score reference only: tournament status, age and official assignment are separate.
 */
object SportRankCatalog {
    const val REVISION = "ru-evsk-201-2026-app34-v1"
    const val SOURCE = "https://minsport.gov.ru/evsk-2026-2029-strelba-iz-luka/"
    const val DOCUMENT = "https://storage.minsport.gov.ru/cms-uploads/cms/Strelba_iz_luka_b944ba5e4d.xls"
    const val SOURCE_SHA256 = "%s"
    val exercises = listOf(
%s
    )
}
''' % (hashlib.sha256(source.read_bytes()).hexdigest(), '\n'.join(lines))
target = ROOT / 'android/app/src/main/java/app/fableshot/android/domain/SportRankCatalog.kt'
target.write_text(code, encoding='utf-8')
print(f'Generated {len(lines)} catalog entries; source SHA256 {hashlib.sha256(source.read_bytes()).hexdigest()}')

# Full numeric table, kept separate from the deliberately narrow auto-match catalog.
# Rows 9..47 contain qualifications; conditions below them must not become scores.
reference = []
title = ''
for row in range(9, 48):
    cells = sheet.row_values(row - 1)
    if cells[1]:
        title = str(cells[1]).strip()
    if str(cells[3]).strip() != 'Очки':
        continue
    group = '3d' if title.startswith('3Д') else 'barebow' if 'бесприцельный' in title else 'compound' if title.startswith('БЛ') else 'recurve'
    values = []
    for offset in (0, 1):
        scores = [cells[4 + 2 * i + offset] for i in range(len(labels))]
        assert all(value == '' or (float(value).is_integer() and float(value) > 0) for value in scores)
        values.append('listOf(' + ', '.join('null' if value == '' else str(int(value)) for value in scores) + ')')
    condition = str(sheet.cell_value(row, 3)).strip() if row < 47 else ''
    if not condition.startswith('Условие:'):
        condition = ''
    quoted = [json.dumps(v, ensure_ascii=False) for v in (group, title, str(cells[2]).strip(), condition)]
    reference.append(f'        RankReferenceRow({row}, ' + ', '.join(quoted + values) + '),')
reference_code = '''package app.fableshot.android.domain

/** Generated from the numeric norms sheet; reference only, including unsupported formats. */
object SportRankReference {
    val labels = listOf(%s)
    val rows = listOf(
%s
    )
}
''' % (', '.join(json.dumps(v, ensure_ascii=False) for v in labels), '\n'.join(reference))
(target.parent / 'SportRankReference.kt').write_text(reference_code, encoding='utf-8')
print(f'Generated {len(reference)} full numeric reference rows (both categories, original blanks).')
